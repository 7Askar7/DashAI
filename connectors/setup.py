"""Generate MCP client config without touching user-wide settings or selecting a model."""

from __future__ import annotations

import argparse
import copy
import json
import os
import re
import sys
import tomllib
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import ProxyHandler, Request, build_opener

if __package__:
    from .mcp_server import NoRedirect, ROOT, connection_options, default_data_dir, load_token
    from .presets import client_profiles, render_config
else:
    from mcp_server import NoRedirect, ROOT, connection_options, default_data_dir, load_token
    from presets import client_profiles, render_config

START = "# BEGIN Agentboard MCP (generated by connectors/setup.py)"
END = "# END Agentboard MCP"


def codex_config(existing: str, entry: dict) -> str:
    """Replace only this server and validate that every other parsed setting survives."""
    before = tomllib.loads(existing)
    expected = copy.deepcopy(before)
    servers = expected.setdefault("mcp_servers", {})
    if not isinstance(servers, dict):
        raise ValueError("mcp_servers must be a TOML table")
    servers["agentboard"] = entry
    retained, dropping = [], False
    for line in existing.splitlines(keepends=True):
        stripped = line.strip()
        if stripped in {START, END}:
            continue
        if re.match(r"^\s*\[.+\]\s*(?:#.*)?$", line):
            header = tomllib.loads(line)
            dropping = isinstance(header.get("mcp_servers"), dict) and "agentboard" in header["mcp_servers"]
        if not dropping:
            retained.append(line)
    block = "\n".join([START, "[mcp_servers.agentboard]", *[
        f"{key} = {json.dumps(value, ensure_ascii=False)}" for key, value in entry.items()
    ], END])
    candidate = "".join(retained).rstrip() + "\n\n" + block + "\n"
    if tomllib.loads(candidate) != expected:
        raise ValueError("Cannot safely update this TOML layout; existing config was left unchanged")
    return candidate


def save(path: Path, content: str, private: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".agentboard.tmp")
    temporary.write_text(content, encoding="utf-8")
    if private:
        os.chmod(temporary, 0o600)
    os.replace(temporary, path)


def setup(project_root: Path, credentials: Path | None = None, base_url: str | None = None,
          agent_name: str | None = None, agent_kind: str = "codex", *,
          executable: Path | None = None, data_dir: Path | None = None,
          client: str = "both", agent_id: str | None = None,
          token_file: Path | None = None) -> tuple[Path, ...]:
    project_root = project_root.resolve()
    if getattr(sys, "frozen", False):
        executable = executable or Path(sys.executable)
        data_dir = data_dir or default_data_dir()
    credentials, base_url = connection_options(credentials, data_dir, base_url)
    if executable is not None:
        executable = executable.resolve()
        if not executable.is_file():
            raise ValueError("Agentboard executable does not exist")
        data_dir = (data_dir or credentials.parent).resolve()
    profiles = ("claude", "codex") if client == "both" else (client,)
    if any(profile not in {p["id"] for p in client_profiles()} for profile in profiles):
        raise ValueError("Unknown MCP client profile")
    if agent_kind not in {"codex", "claude", "custom"}:
        raise ValueError("Invalid agent kind")
    if client == "both" and (agent_kind == "custom" or agent_id or token_file):
        raise ValueError("Select one --client when configuring a separate identity/token")
    if agent_name and (token_file or agent_id):
        raise ValueError("Use --agent-name to issue a new identity or --agent-id/--token-file to reuse one")
    if token_file:
        token_file = token_file.resolve()
    cwd = project_root if executable else ROOT
    configs = {}
    for profile in profiles:
        identity = agent_id or (profile if client == "both" else agent_kind)
        if not agent_name or client == "both" and profile != agent_kind:
            load_token(identity, credentials, token_file)
        configs[profile] = {
            "command": str(executable) if executable else sys.executable,
            "args": ["--mcp" if executable else str(ROOT / "connectors" / "mcp_server.py"),
                     "--agent", identity, "--credentials", str(credentials),
                     *(["--data-dir", str(data_dir)] if data_dir else ["--url", base_url]),
                     *(["--token-file", str(token_file)] if token_file else [])],
        }
    def candidates():
        result = []
        for profile, entry in configs.items():
            rendered = render_config(profile, entry, str(cwd))
            path = project_root / (".dashai" if profile in {"cline", "generic"} else "") / rendered["filename"]
            previous = path.read_text(encoding="utf-8-sig") if path.exists() else ""
            if profile == "codex":
                content = codex_config(previous, {**entry, "cwd": str(cwd)})
            elif profile == "generic":
                if previous and json.loads(previous) != json.loads(rendered["content"]):
                    raise ValueError("Existing generic export differs; choose a new project root or move it first")
                content = rendered["content"]
            else:
                document = json.loads(previous) if previous else {}
                key = "servers" if profile == "vscode" else "mcpServers"
                if not isinstance(document, dict) or not isinstance(document.setdefault(key, {}), dict):
                    raise ValueError(f"{path.name} must contain a {key} object (strict JSON)")
                document[key]["agentboard"] = json.loads(rendered["content"])[key]["agentboard"]
                content = json.dumps(document, ensure_ascii=False, indent=2) + "\n"
            result.append((path, content))
        return result
    candidates()
    # Validate existing configuration before provisioning a one-time credential.
    token_path = None
    if agent_name:
        request = Request(base_url + "/api/agents", method="POST", headers={
            "Content-Type": "application/json", "X-Dashboard-Client": "browser",
        }, data=json.dumps({"name": agent_name, "kind": agent_kind,
                            "reason": "Отдельная идентичность экземпляра coding agent"}, ensure_ascii=False).encode("utf-8"))
        with build_opener(ProxyHandler({}), NoRedirect()).open(request, timeout=15) as response:
            issued = json.load(response)
        token_path = credentials.parent / f"agent-{issued['agent']['id']}.token"
        profile = agent_kind if client == "both" else client
        args = configs[profile]["args"]
        args[args.index("--agent") + 1] = issued["agent"]["id"]
        args += ["--token-file", str(token_path)]
    # Validate every selected config before writing any of them.
    output = candidates()
    if token_path:
        save(token_path, json.dumps(issued, ensure_ascii=False) + "\n", private=True)
    for path, content in output:
        save(path, content)
    return tuple(path for path, _ in output)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path.cwd() if getattr(sys, "frozen", False) else ROOT)
    parser.add_argument("--credentials", type=Path)
    parser.add_argument("--data-dir", type=Path, help="Desktop user's data directory, including runtime.json")
    parser.add_argument("--executable", type=Path, help="Installed Agentboard.exe for project MCP commands")
    parser.add_argument("--url", help="Explicit loopback URL; overrides desktop runtime discovery")
    parser.add_argument("--agent-name", help="Provision one separately attributed coding-agent instance")
    parser.add_argument("--agent", choices=["codex", "claude", "custom"], default="codex", help="Identity kind, independent from client format")
    parser.add_argument("--client", choices=[p["id"] for p in client_profiles()] + ["both"], default="both", help="Client config format; both keeps legacy Codex/Claude setup")
    parser.add_argument("--agent-id", help="Previously issued identity ID; use with --token-file")
    parser.add_argument("--token-file", type=Path, help="Existing issued token/JSON; never embedded in config")
    args = parser.parse_args(argv)
    try:
        paths = setup(args.project_root, args.credentials, args.url, args.agent_name, args.agent,
                      executable=args.executable, data_dir=args.data_dir, client=args.client,
                      agent_id=args.agent_id, token_file=args.token_file)
    except (OSError, ValueError, KeyError, HTTPError, URLError) as error:
        print(f"Agentboard setup: {error}", file=sys.stderr)
        raise SystemExit(1) from None
    for path in paths:
        print(f"Configured: {path}")
    print("Restart your MCP client, discover tools and call list_projects. Configuration is not proof of connection.")
    if args.client in {"cline", "generic"}:
        print("This is a local export: merge it in your client's MCP settings; user-wide config was not changed.")


if __name__ == "__main__":
    main()
